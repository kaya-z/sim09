/*
 * as_text.h - assembler source that as.c puts around the program of the user
 *
 * as_start   in front of the program: the header of the MX file and the start code of lib/crt0app.s (relocates the
 *            program, clears the bss).  The program starts with X = the start-up block of PM (see mklib.h: [1] stdin
 *            handle, [2] stdout handle, [3] argc, [4..] the argument strings) and with a return address on the stack that
 *            leaves the program: "rts" ends it with the exit code in B.  The start-up block is also kept in __sb.
 *            The names __size __bss __stack __end are defined by the assembler.
 * as_runtime behind the program, when the program has the line "runtime": exit putc puts getc open close read write.
 *
 *   exit    B = exit code
 *   putc    A = character, to the standard output (all registers kept)
 *   puts    X = string with a NUL at the end, to the standard output (all registers kept)
 *   getc    -> D = a character from the standard input, or -1 at the end
 *   open    X = path with a NUL, B = FO_* flags (1 read, 2 write, 4 create, 8 truncate, 16 append) -> D = fd (3 up) or -error
 *   close   B = fd -> D = 0 or -error
 *   read    B = fd, X = buffer, Y = length -> D = bytes read (0 at the end of the file) or -error
 *   write   B = fd, X = buffer, Y = length -> D = bytes written or -error
 *   fd 0, 1 and 2 are the standard input, output and error output (redirected by the shell when it was told to).
 */
